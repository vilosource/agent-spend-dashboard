#!/usr/bin/env node
/**
 * Regenerate deploy/docker-compose/postgres/init/003_model_prices.sql from
 * pi-mono's model catalog.
 *
 * The token-tracker server trusts the per-turn cost a harness reports
 * (agent.cost.*.usd). Subscription providers (GitHub Copilot, the Z.AI
 * coding plan, ...) bill flat-rate and report $0 per turn, so the
 * extension tags those rows cost_estimation='subscription'. To surface a
 * meaningful dollar figure for that usage, the /me rollups price the raw
 * token counts at the model's *list* rate — the rates in this table.
 *
 * Source of truth for the rates is pi-mono's models.generated.ts. This
 * script extracts {id, cost:{input,output,cacheRead,cacheWrite}} for every
 * model that carries a non-zero cost, dedupes by model id (keeping the
 * first non-zero occurrence — list prices for a given id are identical
 * across the provider variants we care about, e.g. claude-opus-4-7), and
 * emits idempotent INSERT ... ON CONFLICT seed SQL.
 *
 * Usage:
 *   node scripts/sync-model-prices.mjs [path-to-models.generated.ts]
 *
 * Default path: ~/GitHub/pi-mono/packages/ai/src/models.generated.ts
 * The generated SQL is committed so the lab + prod DBs never need pi-mono.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(HERE, "..");
const OUT = join(REPO_ROOT, "deploy/docker-compose/postgres/init/003_model_prices.sql");

const src = process.argv[2] ?? join(homedir(), "GitHub/pi-mono/packages/ai/src/models.generated.ts");

const text = readFileSync(src, "utf8");

// Each model literal ends with `} satisfies Model<...>`. Split on that
// boundary so every chunk holds exactly one model definition, then pull
// the id + cost block out of the chunk.
const chunks = text.split(/\}\s*satisfies\s+Model</);
const byId = new Map();
let skippedNoCost = 0;

for (const chunk of chunks) {
	const idMatch = chunk.match(/id:\s*"([^"]+)"/);
	if (!idMatch) continue;
	const id = idMatch[1];
	const cost = chunk.match(
		/cost:\s*\{\s*input:\s*([\d.]+)\s*,\s*output:\s*([\d.]+)\s*,\s*cacheRead:\s*([\d.]+)\s*,\s*cacheWrite:\s*([\d.]+)\s*,?\s*\}/,
	);
	if (!cost) {
		skippedNoCost++;
		continue;
	}
	const [input, output, cacheRead, cacheWrite] = cost.slice(1, 5).map(Number);
	if (input === 0 && output === 0 && cacheRead === 0 && cacheWrite === 0) continue; // priced $0 == subscription/free; nothing to estimate
	if (byId.has(id)) continue; // keep first non-zero occurrence
	byId.set(id, { input, output, cacheRead, cacheWrite });
}

const ids = [...byId.keys()].sort();
const rows = ids
	.map((id) => {
		const c = byId.get(id);
		const esc = id.replace(/'/g, "''");
		return `  ('${esc}', ${c.input}, ${c.output}, ${c.cacheRead}, ${c.cacheWrite})`;
	})
	.join(",\n");

const sql = `-- model_prices: per-model list-price rates (USD per 1,000,000 tokens).
--
-- GENERATED by scripts/sync-model-prices.mjs from pi-mono's models.generated.ts.
-- Do not edit by hand; re-run the script to refresh.
--
-- Used by the /me rollups to ESTIMATE the cost of subscription usage
-- (cost_estimation='subscription'), where the provider bills flat-rate and
-- reports $0 per turn. Metered rows keep their provider-reported cost.

CREATE TABLE IF NOT EXISTS model_prices (
   model                  TEXT          PRIMARY KEY,
   input_per_mtok         NUMERIC(12,6) NOT NULL DEFAULT 0,
   output_per_mtok        NUMERIC(12,6) NOT NULL DEFAULT 0,
   cache_read_per_mtok    NUMERIC(12,6) NOT NULL DEFAULT 0,
   cache_write_per_mtok   NUMERIC(12,6) NOT NULL DEFAULT 0,
   source                 TEXT          NOT NULL DEFAULT 'pi-mono:models.generated.ts',
   updated_at             TIMESTAMPTZ   NOT NULL DEFAULT now()
);

INSERT INTO model_prices
   (model, input_per_mtok, output_per_mtok, cache_read_per_mtok, cache_write_per_mtok)
VALUES
${rows}
ON CONFLICT (model) DO UPDATE SET
   input_per_mtok       = EXCLUDED.input_per_mtok,
   output_per_mtok      = EXCLUDED.output_per_mtok,
   cache_read_per_mtok  = EXCLUDED.cache_read_per_mtok,
   cache_write_per_mtok = EXCLUDED.cache_write_per_mtok,
   updated_at           = now();
`;

writeFileSync(OUT, sql);
console.error(
	`wrote ${OUT}\n  ${ids.length} priced models from ${src}\n  (${skippedNoCost} model chunks had no cost block — subscription/omitted)`,
);
